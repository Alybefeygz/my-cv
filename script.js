const dialog = document.querySelector("#project-dialog");
const dialogTitle = document.querySelector("#dialog-title");
const dialogEyebrow = document.querySelector("#dialog-eyebrow");
const dialogBody = document.querySelector("#dialog-body");
const dialogActions = document.querySelector("#dialog-actions");
const dialogClose = document.querySelector(".dialog-close");
let lastProjectTrigger = null;

function createTextElement(tagName, className, text) {
  const element = document.createElement(tagName);
  if (className) element.className = className;
  element.textContent = text;
  return element;
}

function renderProjectDetails(detail) {
  dialogBody.replaceChildren();

  if (detail.image) {
    const image = document.createElement("img");
    image.className = "dialog-media";
    image.src = detail.image;
    image.alt = detail.imageAlt || "";
    dialogBody.append(image);
  }

  detail.sections.forEach((section) => {
    const sectionElement = document.createElement("section");
    sectionElement.className = "dialog-section";
    sectionElement.append(createTextElement("h3", "", section.title));

    section.body?.forEach((paragraph) => {
      sectionElement.append(createTextElement("p", "", paragraph));
    });

    if (section.list) {
      const list = document.createElement("ul");
      section.list.forEach((item) => {
        list.append(createTextElement("li", "", item));
      });
      sectionElement.append(list);
    }

    dialogBody.append(sectionElement);
  });

  if (detail.tags?.length) {
    const tagSection = document.createElement("section");
    tagSection.className = "dialog-section";
    tagSection.append(createTextElement("h3", "", "Teknolojiler"));

    const tags = document.createElement("div");
    tags.className = "dialog-tags";
    detail.tags.forEach((tag) => {
      tags.append(createTextElement("span", "", tag));
    });

    tagSection.append(tags);
    dialogBody.append(tagSection);
  }
}

function createDocumentPlaceholder(page) {
  const placeholder = document.createElement("div");
  placeholder.className = "document-placeholder";
  placeholder.append(createTextElement("span", "", page.label));
  placeholder.append(createTextElement("strong", "", page.title));
  placeholder.append(createTextElement("p", "", page.note || "Belge dosyası eklendiğinde burada görüntülenecek."));
  return placeholder;
}

function renderDocumentPage(stage, thumbs, pages, pageIndex) {
  const page = pages[pageIndex];
  stage.replaceChildren();
  thumbs.forEach((thumb, thumbIndex) => {
    thumb.classList.toggle("is-active", thumbIndex === pageIndex);
  });

  const pageFrame = document.createElement("div");
  pageFrame.className = "document-page";

  if (page.type === "image" && page.src) {
    const image = document.createElement("img");
    image.src = page.src;
    image.alt = page.title;
    image.addEventListener("error", () => {
      pageFrame.replaceChildren(createDocumentPlaceholder(page));
    });
    pageFrame.append(image);
  } else if (page.type === "pdf" && page.src) {
    const documentFile = document.createElement("object");
    documentFile.className = "document-file";
    documentFile.data = page.src;
    documentFile.type = "application/pdf";
    documentFile.append(createDocumentPlaceholder(page));
    pageFrame.append(documentFile);
  } else {
    pageFrame.append(createDocumentPlaceholder(page));
  }

  const caption = document.createElement("div");
  caption.className = "document-caption";
  caption.append(createTextElement("span", "", page.title));
  caption.append(createTextElement("span", "", `${pageIndex + 1} / ${pages.length}`));

  stage.append(pageFrame, caption);
}

function renderDocumentViewer(detail) {
  dialogBody.replaceChildren();

  const pages = detail.pages || [];

  const viewer = document.createElement("div");
  viewer.className = `document-viewer${pages.length <= 1 ? " is-single-page" : ""}`;

  const thumbList = document.createElement("div");
  thumbList.className = "document-thumbs";

  const stage = document.createElement("div");
  stage.className = "document-stage";

  const thumbButtons = pages.map((page, pageIndex) => {
    const thumb = document.createElement("button");
    thumb.className = "document-thumb";
    thumb.type = "button";
    thumb.setAttribute("aria-label", `${page.title} belgesini göster`);

    const preview = document.createElement("span");
    preview.className = "document-thumb-preview";

    if (page.type === "image" && page.src) {
      const image = document.createElement("img");
      image.src = page.src;
      image.alt = "";
      image.addEventListener("error", () => {
        preview.replaceChildren(createTextElement("span", "", String(pageIndex + 1).padStart(2, "0")));
      });
      preview.append(image);
    } else {
      preview.append(createTextElement("span", "", String(pageIndex + 1).padStart(2, "0")));
    }

    thumb.append(preview, createTextElement("small", "", page.label));
    thumb.addEventListener("click", () => renderDocumentPage(stage, thumbButtons, pages, pageIndex));
    thumbList.append(thumb);
    return thumb;
  });

  viewer.append(thumbList, stage);
  dialogBody.append(viewer);

  if (pages.length) renderDocumentPage(stage, thumbButtons, pages, 0);
}

function renderDialogActions(detail) {
  dialogActions?.replaceChildren();

  if (!detail.download || !dialogActions) return;

  const downloadLink = document.createElement("a");
  downloadLink.className = "document-download";
  downloadLink.href = detail.download.href;
  downloadLink.download = detail.download.filename || "";
  downloadLink.textContent = detail.download.label || "Belgeyi İndir";

  dialogActions.append(downloadLink);
}

function openProjectDialog(trigger) {
  const detail = projectDetails[trigger.dataset.project];

  if (!detail || !dialog) return;

  lastProjectTrigger = trigger;
  dialog.classList.remove("is-document-dialog");
  dialogEyebrow.textContent = detail.meta;
  dialogTitle.textContent = detail.title;
  dialogActions?.replaceChildren();
  renderProjectDetails(detail);
  dialog.showModal();
  dialog.scrollTop = 0;
  document.body.classList.add("dialog-open");
  dialogClose?.focus();
}

document.querySelectorAll("[data-project]").forEach((trigger) => {
  trigger.addEventListener("click", () => {
    openProjectDialog(trigger);
  });

  if (trigger.tagName !== "BUTTON") {
    trigger.addEventListener("keydown", (event) => {
      if (event.key !== "Enter" && event.key !== " ") return;
      event.preventDefault();
      openProjectDialog(trigger);
    });
  }
});

function openDocumentDialog(trigger) {
  const detail = documentDetails[trigger.dataset.document];

  if (!detail || !dialog) return;

  lastProjectTrigger = trigger;
  dialog.classList.add("is-document-dialog");
  dialogEyebrow.textContent = detail.meta;
  dialogTitle.textContent = detail.title;
  renderDialogActions(detail);
  renderDocumentViewer(detail);
  dialog.showModal();
  dialog.scrollTop = 0;
  document.body.classList.add("dialog-open");
  dialogClose?.focus();
}

document.querySelectorAll("[data-document]").forEach((trigger) => {
  trigger.addEventListener("click", () => {
    openDocumentDialog(trigger);
  });
});

function closeProjectDialog() {
  if (!dialog?.open) return;
  dialog.close();
}

dialogClose?.addEventListener("click", closeProjectDialog);

dialog?.addEventListener("click", (event) => {
  if (event.target === dialog) closeProjectDialog();
});

dialog?.addEventListener("close", () => {
  document.body.classList.remove("dialog-open");
  dialog.classList.remove("is-document-dialog");

  if (lastProjectTrigger) {
    lastProjectTrigger.focus();
    lastProjectTrigger = null;
  }
});

const educationCards = Array.from(document.querySelectorAll(".education-card"));
const educationDots = Array.from(document.querySelectorAll(".slider-dots button"));

function showEducationGroup(index) {
  educationCards.forEach((card, cardIndex) => {
    const shouldShow = cardIndex >= index * 2 && cardIndex < index * 2 + 2;
    card.hidden = !shouldShow;
    card.classList.toggle("is-visible", shouldShow);
  });

  educationDots.forEach((dot, dotIndex) => {
    dot.classList.toggle("is-active", dotIndex === index);
  });
}

educationDots.forEach((dot) => {
  dot.addEventListener("click", () => {
    showEducationGroup(Number(dot.dataset.slide));
  });
});
